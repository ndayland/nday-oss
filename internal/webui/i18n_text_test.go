var update = flag.Bool("update", false, "rewrite testdata/golden/<locale>.txt")

// goldenText renders every rule-generated text of the fixed scenarios in l,
// with the message keys each one was built from.
func goldenText(l *i18n.Locale) string {
	var b strings.Builder
	keys := func(ms []Msg) string {
		var ks []string
		for _, m := range ms {
			ks = append(ks, m.Key)
		}
		return strings.Join(ks, " + ")
	}
	fmt.Fprintf(&b, "# %s (%s) — generated by go test ./internal/webui -run TestGolden -update; reviewed by native speakers\n\n", l.Tag, l.NativeName)
	b.WriteString("## status paragraph (vulnerability page)\n\n")
	for _, s := range StatusScenarios() {
		ms := StatusMessages(s.V)
		fmt.Fprintf(&b, "### %s\nkeys: %s\n%s\n\n", s.Name, keys(ms), StatusSentence(l, s.V))
	}
	b.WriteString("## event text (event log)\n\n")
	for _, s := range EventScenarios() {
		fmt.Fprintf(&b, "### %s\nkeys: %s\n%s\n\n", s.Name, keys(EventMessages(s.E)), html.UnescapeString(string(EventText(l, s.E))))
	}
	b.WriteString("## formatting\n\n")
	for d := 9; d <= 15; d++ {
		fmt.Fprintf(&b, "date group: %s\n", DateGroupLabel(l, time.Date(2026, 11, d, 12, 0, 0, 0, time.UTC)))
	}
	for _, n := range []int64{0, 1, 999, 1000, 45965, 1234567} {
		fmt.Fprintf(&b, "number %d: %s\n", n, l.Int(n))
	}
	for _, p := range []string{"exact", "observed", "day", "unknown"} {
		fmt.Fprintf(&b, "precision %s: %q / %q\n", p, PrecisionShort(l, p), PrecisionNote(l, p))
	}
	for _, d := range []*int{nil, scInt(0), scInt(1), scInt(5), scInt(-1), scInt(-20)} {
		fmt.Fprintf(&b, "T+ %s: %s\n", FormatTPlus(d), TPlusTitle(l, d))
	}
	strip := BuildStrip(l, []site.Slot{{Code: "DIS", State: "known"}, {Code: "PAT", State: "none"}, {Code: "ANA", State: "none"},
		{Code: "POC", State: "unknown"}, {Code: "ITW", State: "implied"}, {Code: "KEV", State: "known", Latest: true}})
	fmt.Fprintf(&b, "strip: %s\nstrip empty: %s\n", strip.Label, BuildStrip(l, nil).Label)
	ps := []site.Product{{Vendor: "Barracuda Networks", Product: "ESG"}, {Vendor: "Barracuda Networks", Product: "Load Balancer ADC"}}
	p1, _ := ProductLine(l, ps, 3, 2)
	p2, _ := ProductLine(l, nil, 1, 2)
	p3, _ := ProductLine(l, nil, 4, 2)
	fmt.Fprintf(&b, "products: %s | %s | %s\n", p1, p2, p3)
	for _, n := range []int{1, 2, 6} {
		fmt.Fprintf(&b, "events %d: %s | sources %d: %s\n", n, l.Text("sbar.events", "n", n), n, l.Text("sbar.sources", "n", n))
	}
	return b.String()
}

// TestGolden: the generated texts of every enabled locale match
// testdata/golden/<tag>.txt. A writer of a new locale creates the file with
// -update and has it reviewed; afterwards any change shows up as a diff.
func TestGolden(t *testing.T) {
	set, err := i18n.Default()
	if err != nil {
		t.Fatal(err)
	}
	for _, l := range set.Enabled {
		got := goldenText(l)
		if strings.Contains(got, i18n.MissingOpen) {
			t.Errorf("%s: missing message in generated text", l.Tag)
		}
		path := filepath.Join("testdata", "golden", l.Tag+".txt")
		if *update {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Errorf("%s: no golden file (run: go test ./internal/webui -run TestGolden -update): %v", l.Tag, err)
			continue
		}
		if string(want) != got {
			t.Errorf("%s: generated text differs from %s (review, then -update):\n%s", l.Tag, path, firstDiff(string(want), got))
		}
	}
}

func firstDiff(a, b string) string {
	al, bl := strings.Split(a, "\n"), strings.Split(b, "\n")
	for i := 0; i < len(al) || i < len(bl); i++ {
		var x, y string
		if i < len(al) {
			x = al[i]
		}
		if i < len(bl) {
			y = bl[i]
		}
		if x != y {
			return fmt.Sprintf("line %d:\n- %s\n+ %s", i+1, x, y)
		}
	}
	return ""
}

// probeLocale is a locale whose every message is "‹key[variant] {p}…›":
// whatever Go adds outside a message shows up as text outside the brackets.
func probeLocale(t *testing.T) *i18n.Locale {
	t.Helper()
	src := i18n.Embedded()
	m := fstest.MapFS{}
	for _, n := range []string{"locales.json", "keys.json", "catalogs/en.json"} {
		b, err := fs.ReadFile(src, n)
		if err != nil {
			t.Fatal(err)
		}
		m[n] = &fstest.MapFile{Data: b}
	}
	set, err := i18n.Load(m)
	if err != nil {
		t.Fatal(err)
	}
	ref := set.Reference
	msgs := map[string]any{}
	for _, k := range ref.Keys() {
		d := ref.Key(k)
		var phs []string
		for n := range d.Placeholders {
			phs = append(phs, "{"+n+"}")
		}
		sort.Strings(phs)
		text := func(v string) string {
			if v != "" {
				v = "[" + v + "]"
			}
			return "‹" + k + v + " " + strings.Join(phs, " ") + "›"
		}
		switch {
		case d.Plural != "":
			msgs[k] = text("")
		case d.Select != nil:
			vs := map[string]string{}
			for _, v := range d.Select.Values {
				vs[v] = text(v)
			}
			msgs[k] = vs
		default:
			msgs[k] = text("")
		}
	}
	b, _ := json.Marshal(map[string]any{"locale": "ja", "messages": msgs}) // a plural-less registry entry
	m["catalogs/ja.json"] = &fstest.MapFile{Data: b}
	set, err = i18n.Load(m)
	if err != nil {
		t.Fatal(err)
	}
	return set.ByTag("ja") // disabled (probe texts break typography rules) but renderable
}

var innermost = regexp.MustCompile(`‹[^‹›]*›`)

// onlyMessages reports text that is not inside a probe message.
func onlyMessages(s string) string {
	for {
		n := innermost.ReplaceAllString(s, "")
		if n == s {
			return s
		}
		s = n
	}
}

// TestGeneratedTextIsCatalogOnly: with the probe catalog, the status
// paragraph, event texts, strip labels, chart labels and feed summaries
// consist of catalog messages only — no word, particle, punctuation or
// spacing is added by Go.
func TestGeneratedTextIsCatalogOnly(t *testing.T) {
	p := probeLocale(t)
	check := func(what, s string) {
		t.Helper()
		if !strings.Contains(s, "‹") {
			t.Errorf("%s: no message at all: %q", what, s)
		}
		if rest := onlyMessages(s); rest != "" {
			t.Errorf("%s: text outside catalog messages %q in %q", what, rest, s)
		}
	}
	for _, s := range StatusScenarios() {
		check("status/"+s.Name, StatusSentence(p, s.V))
	}
	for _, s := range EventScenarios() {
		check("event/"+s.Name, string(EventText(p, s.E)))
	}
	strip := BuildStrip(p, []site.Slot{{Code: "DIS", State: "known"}, {Code: "POC", State: "unknown"}, {Code: "KEV", State: "known", Latest: true}})
	check("strip", strip.Label)
	check("strip empty", BuildStrip(p, nil).Label)
	for _, d := range []*int{nil, scInt(1), scInt(-3)} {
		check("tplus title", TPlusTitle(p, d))
	}
	check("date group", DateGroupLabel(p, time.Date(2026, 11, 12, 0, 0, 0, 0, time.UTC)))
	v := gpuDetail()
	c := BuildChart(p, v, time.Date(2026, 11, 13, 2, 30, 0, 0, time.UTC))
	for _, r := range c.Rows {
		check("chart aria "+r.Code, r.Aria)
	}
	vv := BuildVulnView(p, v, time.Date(2026, 11, 13, 2, 30, 0, 0, time.UTC), NewAPI("https://nday.land", ""))
	for _, ev := range vv.Events {
		if !ev.Implied {
			check("event obs", string(ev.Obs))
		} else {
			check("implied basis", string(ev.BasisHTML))
		}
		if ev.TimeNote != "" { // no note when the source gave the exact time
			check("event time note", ev.TimeNote)
		}
		check("event text", string(ev.Text))
	}
	for _, f := range vv.Facts {
		check("fact label", f.Label)
	}
	page := &site.HotPage{Rows: []site.HotRow{{CVEID: "CVE-2026-1", Title: scStr("t"), Transition: site.Transition{Code: "KEV",
		At: time.Date(2026, 11, 9, 0, 0, 0, 0, time.UTC), Precision: "day"}, DaysSinceDisclosure: scInt(5),
		Products: []site.Product{{Vendor: "v", Product: "p"}}, ProductCount: 1}}}
	body, err := BuildFeed(p, page, "https://nday.land", time.Now())
	if err != nil {
		t.Fatal(err)
	}
	sum := regexp.MustCompile(`<summary type="text">([^<]*)</summary>`).FindStringSubmatch(string(body))
	if sum == nil {
		t.Fatal("no feed summary")
	}
	check("feed summary", strings.NewReplacer("&#39;", "'", "&#34;", `"`, "&amp;", "&").Replace(sum[1]))
}
