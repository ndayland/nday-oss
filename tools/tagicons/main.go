// Command tagicons generates the tag icon sprite and its mask stylesheet:
//
//	internal/webui/static/tagicons.svg  one <symbol> per distinct icon
//	internal/webui/static/tagicons.css  the same icons as CSS masks (the
//	                                    fallback rendering, see
//	                                    internal/webui/tagicons.go)
//
// from the mapping tags.Icons (internal/tags/icons.go) and the icons
// directory of a Simple Icons release (https://simpleicons.org, CC0-1.0),
// downloaded and unpacked by hand into a scratch directory and passed by
// path. Nothing from the package is copied except the path data of the
// icons the mapping names:
//
//	DIR=/abs/scratch/simple-icons; mkdir "$DIR"
//	(download the simple-icons npm tarball of a release and unpack it into $DIR)
//	go run ./tools/tagicons -icons "$DIR/package/icons" -data "$DIR/package/data/simple-icons.json"
//
// With -data, the program also prints, for review, each icon's title in
// the package's data file and any licence the data names for it other than
// the package's CC0-1.0 (those icons need an entry in
// internal/webui/static/tagicons.NOTICE).
//
// Every icon file must have exactly the shape Simple Icons ships (an <svg>
// with a 24x24 viewBox, a <title> and one <path>); anything else is
// rejected. Only the path's d attribute is kept, after checking it against a
// strict character class for SVG path data and a size cap. Titles, colours
// and everything else are dropped. Output is sorted and deterministic, so
// regenerating from the same release changes nothing.
//
// The program never touches the network, runs nothing from the package and
// is not part of the server. See docs/tagicons.md.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"nday.land/nday/internal/tags"
)

// MaxPath is the size cap of one icon's path data, in bytes.
const MaxPath = 12 << 10

var (
	// fileRe is the exact shape of a Simple Icons file.
	fileRe = regexp.MustCompile(`^<svg role="img" viewBox="0 0 24 24" xmlns="http://www\.w3\.org/2000/svg"><title>[^<>]*</title><path d="([^"<>]*)"/></svg>\s*$`)
	// pathRe is the character class of SVG path data: commands, numbers,
	// separators.
	pathRe = regexp.MustCompile(`^[MmZzLlHhVvCcSsQqTtAa0-9.,+\-eE \t\r\n]+$`)
	// idRe is the shape of a Simple Icons slug used as a symbol id.
	idRe = regexp.MustCompile(`^[a-z0-9]+$`)
	wsRe = regexp.MustCompile(`[ \t\r\n]+`)
)

// ErrTooLarge marks an icon over MaxPath (reported and skipped).
var ErrTooLarge = errors.New("path data over the size cap")

// extractPath returns the path data of one Simple Icons file.
func extractPath(svg []byte) (string, error) {
	m := fileRe.FindSubmatch(svg)
	if m == nil {
		return "", errors.New("not exactly <svg viewBox=\"0 0 24 24\"><title/><path d/></svg>")
	}
	d := strings.TrimSpace(wsRe.ReplaceAllString(string(m[1]), " "))
	if d == "" || !pathRe.MatchString(d) {
		return "", errors.New("path data has characters outside the path grammar")
	}
	if d[0] != 'M' && d[0] != 'm' {
		return "", errors.New("path data does not start with a moveto")
	}
	if len(d) > MaxPath {
		return "", fmt.Errorf("%w: %d bytes", ErrTooLarge, len(d))
	}
	return d, nil
}

// load reads the icons the mapping names from dir: id -> path data. Icons
// over the size cap are skipped and listed in skipped; any other problem is
// an error.
func load(dir string, mapping map[string]string) (icons map[string]string, skipped []string, err error) {
	icons = map[string]string{}
	ids := map[string]bool{}
	for _, id := range mapping {
		ids[id] = true
	}
	for _, id := range sortedKeys(ids) {
		if !idRe.MatchString(id) {
			return nil, nil, fmt.Errorf("icon id %q: not a plain slug", id)
		}
		b, err := os.ReadFile(filepath.Join(dir, id+".svg"))
		if err != nil {
			return nil, nil, err
		}
		d, err := extractPath(b)
		if errors.Is(err, ErrTooLarge) {
			skipped = append(skipped, id+": "+err.Error())
			continue
		}
		if err != nil {
			return nil, nil, fmt.Errorf("%s.svg: %w", id, err)
		}
		icons[id] = d
	}
	return icons, skipped, nil
}

// sprite renders the <symbol> sprite.
func sprite(icons map[string]string) []byte {
	var b bytes.Buffer
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg">` + "\n")
	b.WriteString("<!-- generated by tools/tagicons from Simple Icons (CC0-1.0); see tagicons.NOTICE -->\n")
	for _, id := range sortedKeys(icons) {
		fmt.Fprintf(&b, `<symbol id="%s" viewBox="0 0 24 24"><path d="%s"/></symbol>`+"\n", id, icons[id])
	}
	b.WriteString("</svg>\n")
	return b.Bytes()
}

// maskCSS renders the mask stylesheet: one rule per icon, the icon as a
// percent-encoded data: URL.
func maskCSS(icons map[string]string) []byte {
	var b bytes.Buffer
	b.WriteString("/* generated by tools/tagicons from Simple Icons (CC0-1.0); see tagicons.NOTICE */\n")
	for _, id := range sortedKeys(icons) {
		u := `url("data:image/svg+xml,` + dataEscape(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'><path d='`+icons[id]+`'/></svg>`) + `")`
		fmt.Fprintf(&b, ".tgi[data-i=\"%s\"]{-webkit-mask-image:%s;mask-image:%s}\n", id, u, u)
	}
	return b.Bytes()
}

// dataEscape percent-encodes s for a data: URL inside a double-quoted CSS
// url(): only characters that need no quoting in either are kept.
func dataEscape(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9', strings.IndexByte(".,-+=/:'", c) >= 0:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "%%%02X", c)
		}
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// iconData is the part of an entry of simple-icons.json the review needs.
type iconData struct {
	Title   string `json:"title"`
	Slug    string `json:"slug"`
	License *struct {
		Type string `json:"type"`
		URL  string `json:"url"`
	} `json:"license"`
}

// review lists, for each icon used, its title and any licence other than
// CC0-1.0 the data file names; an icon missing from the data is an error.
func review(dataFile string, icons map[string]string) ([]string, error) {
	b, err := os.ReadFile(dataFile)
	if err != nil {
		return nil, err
	}
	var all []iconData
	if err := json.Unmarshal(b, &all); err != nil {
		return nil, err
	}
	bySlug := map[string]iconData{}
	for _, d := range all {
		bySlug[d.Slug] = d
	}
	var out []string
	for _, id := range sortedKeys(icons) {
		d, ok := bySlug[id]
		if !ok {
			return nil, fmt.Errorf("icon %s is not in %s", id, dataFile)
		}
		line := fmt.Sprintf("%-20s %q", id, d.Title)
		if d.License != nil && d.License.Type != "CC0-1.0" {
			line += " licence " + d.License.Type + " " + d.License.URL
		}
		out = append(out, line)
	}
	return out, nil
}

func main() {
	dir := flag.String("icons", "", "the icons/ directory of an unpacked Simple Icons package (required)")
	outSVG := flag.String("svg", "internal/webui/static/tagicons.svg", "sprite output")
	outCSS := flag.String("css", "internal/webui/static/tagicons.css", "mask stylesheet output")
	data := flag.String("data", "", "the package's data/simple-icons.json: print titles and licences for review (optional)")
	flag.Parse()
	if *dir == "" {
		flag.Usage()
		os.Exit(2)
	}
	icons, skipped, err := load(*dir, tags.Icons)
	if err != nil {
		fmt.Fprintln(os.Stderr, "tagicons:", err)
		os.Exit(1)
	}
	for _, s := range skipped {
		fmt.Fprintln(os.Stderr, "tagicons: skipped", s)
	}
	if *data != "" {
		lines, err := review(*data, icons)
		if err != nil {
			fmt.Fprintln(os.Stderr, "tagicons:", err)
			os.Exit(1)
		}
		for _, l := range lines {
			fmt.Fprintln(os.Stderr, l)
		}
	}
	if err := os.WriteFile(*outSVG, sprite(icons), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "tagicons:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outCSS, maskCSS(icons), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "tagicons:", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "tagicons: %d symbols for %d tags\n", len(icons), len(tags.Icons))
}
