func TestReview(t *testing.T) {
	f := filepath.Join(t.TempDir(), "data.json")
	data := `[{"title":"Acme","slug":"acme","hex":"000000","source":"x"},
	{"title":"Zed","slug":"zed","hex":"000000","source":"x","license":{"type":"CC-BY-4.0"}},
	{"title":"Free","slug":"free","hex":"000000","source":"x","license":{"type":"CC0-1.0"}}]`
	if err := os.WriteFile(f, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
	lines, err := review(f, map[string]string{"zed": "M0 0z", "acme": "M0 0z", "free": "M0 0z"})
	if err != nil || len(lines) != 3 || !strings.HasPrefix(lines[0], "acme") || strings.Contains(lines[0], "licence") ||
		!strings.Contains(lines[2], `"Zed" licence CC-BY-4.0`) || strings.Contains(lines[1], "licence") {
		t.Errorf("%q %v", lines, err)
	}
	if _, err := review(f, map[string]string{"other": "M0 0z"}); err == nil {
		t.Error("icon missing from the data accepted")
	}
}
