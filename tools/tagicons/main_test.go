const head = `<svg role="img" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><title>X</title>`

func TestExtractPath(t *testing.T) {
	d, err := extractPath([]byte(head + `<path d="M0 0h24v24H0z  m1.5-2e-1 3,4"/></svg>` + "\n"))
	if err != nil || d != "M0 0h24v24H0z m1.5-2e-1 3,4" {
		t.Fatalf("%q %v", d, err)
	}
	for name, svg := range map[string]string{
		"two paths":      head + `<path d="M0 0h1z"/><path d="M1 1h1z"/></svg>`,
		"no path":        head + `</svg>`,
		"other viewBox":  strings.Replace(head, "0 0 24 24", "0 0 48 48", 1) + `<path d="M0 0h1z"/></svg>`,
		"fill attribute": head + `<path fill="red" d="M0 0h1z"/></svg>`,
		"script":         head + `<path d="M0 0h1z"/><script>alert(1)</script></svg>`,
		"style":          `<svg role="img" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" style="x"><title>X</title><path d="M0 0h1z"/></svg>`,
		"markup in d":    head + `<path d="M0 0h1z'/><script/>"/></svg>`,
		"url in d":       head + `<path d="M0 0 url(#x)"/></svg>`,
		"no moveto":      head + `<path d="L0 0h1z"/></svg>`,
		"empty d":        head + `<path d=""/></svg>`,
		"semicolon":      head + `<path d="M0 0;h1z"/></svg>`,
		"trailing junk":  head + `<path d="M0 0h1z"/></svg><x/>`,
	} {
		if d, err := extractPath([]byte(svg)); err == nil {
			t.Errorf("%s: accepted %q", name, d)
		}
	}
	big := head + `<path d="M0 0` + strings.Repeat("h1", MaxPath) + `"/></svg>`
	if _, err := extractPath([]byte(big)); !errors.Is(err, ErrTooLarge) {
		t.Errorf("oversize: %v", err)
	}
}

func TestLoadAndOutputs(t *testing.T) {
	dir := t.TempDir()
	write := func(name, s string) {
		if err := os.WriteFile(filepath.Join(dir, name+".svg"), []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("acme", head+`<path d="M1 1h2v2H1z"/></svg>`)
	write("zed", head+`<path d="M0 0h24v24H0z"/></svg>`)
	write("huge", head+`<path d="M0 0`+strings.Repeat("h1", MaxPath)+`"/></svg>`)
	mapping := map[string]string{"a-1": "zed", "a-2": "acme", "a-3": "acme", "a-4": "huge"}
	icons, skipped, err := load(dir, mapping)
	if err != nil {
		t.Fatal(err)
	}
	if len(icons) != 2 || len(skipped) != 1 || !strings.HasPrefix(skipped[0], "huge: ") {
		t.Fatalf("icons %v skipped %v", icons, skipped)
	}
	svg := sprite(icons)
	want := `<svg xmlns="http://www.w3.org/2000/svg">` + "\n" +
		"<!-- generated by tools/tagicons from Simple Icons (CC0-1.0); see tagicons.NOTICE -->\n" +
		`<symbol id="acme" viewBox="0 0 24 24"><path d="M1 1h2v2H1z"/></symbol>` + "\n" +
		`<symbol id="zed" viewBox="0 0 24 24"><path d="M0 0h24v24H0z"/></symbol>` + "\n</svg>\n"
	if string(svg) != want {
		t.Errorf("sprite\n%s", svg)
	}
	css := maskCSS(icons)
	if !bytes.Contains(css, []byte(`.tgi[data-i="acme"]{-webkit-mask-image:url("data:image/svg+xml,%3Csvg%20xmlns='http://www.w3.org/2000/svg'%20viewBox='0%200%2024%2024'%3E%3Cpath%20d='M1%201h2v2H1z'/%3E%3C/svg%3E");mask-image:url("data:image/svg+xml,`)) {
		t.Errorf("css\n%s", css)
	}
	// deterministic: the same input gives the same bytes
	for i := 0; i < 5; i++ {
		again, _, _ := load(dir, mapping)
		if !bytes.Equal(sprite(again), svg) || !bytes.Equal(maskCSS(again), css) {
			t.Fatal("output differs between runs")
		}
	}
	// a missing file or a bad id is an error, not a silent gap
	if _, _, err := load(dir, map[string]string{"x": "missing"}); err == nil {
		t.Error("missing icon accepted")
	}
	if _, _, err := load(dir, map[string]string{"x": "../acme"}); err == nil {
		t.Error("path in id accepted")
	}
	write("bad", head+`<path d="M0 0h1z"/><path d="M1 1z"/></svg>`)
	if _, _, err := load(dir, map[string]string{"x": "bad"}); err == nil {
		t.Error("two-path icon accepted")
	}
}

